# what is venv or virtual environment 
# venv is a directory that contains a copy of the python interpreter and the python packages
# venv is used to create a isolated environment for a project

# python -m venv venv/azad/anyName and that will be your venv name
# to activate the venv, we use the following command:
# source venv/bin/activate (on linux and mac)
# venv\Scripts\activate (on windows) 
# power shell: .\venv\Scripts\Activate.ps1 (on windows)
# to deactivate the venv, we use the following command:
# deactivate (on linux and mac)
# .\venv\Scripts\Deactivate.ps1 (on windows)
# power shell: deactivate (on windows)
# to list the packages in the venv, we use the following command:
# pip list (on linux and mac)
# .\venv\Scripts\pip list (on windows)
# power shell: pip list (on windows)
# to install a package in the venv, we use the following command:
# pip install package_name (on linux and mac)
# .\venv\Scripts\pip install package_name (on windows)
# power shell: pip install package_name (on windows)
# to uninstall a package in the venv, we use the following command:
# pip uninstall package_name (on linux and mac)